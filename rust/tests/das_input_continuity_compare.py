#!/usr/bin/env python3
"""Differential checks of optional DAS continuity metadata, never a DAS build.

check --producer SCRIPT --binary PRIVA --work-root NEW_DIRECTORY
oracle --producer SCRIPT --exception JSON -- ORIGINAL_ARGUMENTS

Generated byte-sized inputs and independent pinned proof files exercise the
original checker. Compare exit, stdout, exception category/message, certificate
bytes/mode, source preservation and cross-language checking. Unqualified JSON
profiles are recorded separately; their differences are never tolerances.
"""
from __future__ import annotations
import argparse
import copy
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import stat
import subprocess
import sys
import time
from types import SimpleNamespace

sys.dont_write_bytecode = True


def save(path, value):
    with Path(path).open('x') as stream:
        json.dump(value, stream, sort_keys=True, indent=2)
        stream.write('\n')


def load_producer(path):
    sys.path.insert(0, str(path.parent))
    spec = importlib.util.spec_from_file_location('continuity_reference', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def oracle(args):
    module = load_producer(args.producer)
    observed = {}
    def trace(frame, event, value):
        if event == 'exception' and frame.f_code.co_filename in (
                str(args.producer), str(args.producer.parent/'das_install_state.py')):
            category, error, _ = value
            if category is not SystemExit:
                observed.update(category=category.__name__, message=str(error))
        return trace
    sys.argv = [str(args.producer), *args.arguments]
    sys.settrace(trace)
    try:
        result = module.main()
    except Exception:
        result = 1
    finally:
        sys.settrace(None)
        if observed:
            save(args.exception, observed)
    raise SystemExit(result)


def snapshot(paths):
    result = {}
    for path in paths:
        info = path.lstat()
        payload = os.fsencode(os.readlink(path)) if path.is_symlink() else path.read_bytes()
        result[str(path)] = [info.st_ino, info.st_size, info.st_mtime_ns, info.st_mode,
                             hashlib.sha256(payload).hexdigest()]
    return result


def check(args):
    root = args.work_root.absolute(); root.mkdir()
    producer, binary = args.producer.absolute(), args.binary.absolute()
    module = load_producer(producer)
    result = {'cases': [], 'unqualified': [], 'producer_sha256': hashlib.sha256(producer.read_bytes()).hexdigest(),
              'binary_sha256': hashlib.sha256(binary.read_bytes()).hexdigest()}
    counter = 0
    def run(base, arguments, language):
        nonlocal counter
        counter += 1; folder = base/f'call_{counter:04d}_{language}'; folder.mkdir()
        if language == 'python':
            command = [sys.executable, str(Path(__file__).absolute()), 'oracle', '--producer', str(producer),
                       '--exception', str(folder/'exception.json'), '--', *arguments]
        else:
            command = [str(binary), 'das-input-continuity', *arguments,
                       '--checker-source', str(producer)]
        started = time.monotonic()
        outcome = subprocess.run(command, cwd=base, capture_output=True, timeout=30,
            env=dict(os.environ, PYTHONDONTWRITEBYTECODE='1', POLARS_MAX_THREADS='1', OMP_NUM_THREADS='1'))
        (folder/'stdout.log').write_bytes(outcome.stdout); (folder/'stderr.log').write_bytes(outcome.stderr)
        row = {'exit': outcome.returncode, 'stdout': outcome.stdout.decode(), 'seconds': time.monotonic()-started}
        if outcome.returncode == 1:
            if language == 'python' and (folder/'exception.json').exists():
                row.update(json.loads((folder/'exception.json').read_text()))
            else:
                match = re.search(r'(?:^|\n)(?:priva: )?([A-Za-z]+Error): (.*)', outcome.stderr.decode(), re.S)
                row.update(category=match[1] if match else None,
                           message=match[2].rstrip('\n') if match else outcome.stderr.decode())
        return row

    def pair(base, arguments, name, *, unqualified=False):
        protected = [base/name for name in ('old.bin','new.bin','analysis.py','bundle.bin','out.bin','receipt.json','proof.json','plan.json','comparison.json','publication.json')]
        protected = [p for p in protected if p.is_file() or p.is_symlink()]
        before = snapshot(protected)
        py = run(base, arguments, 'python')
        published = [p for p in base.glob('continuity.json*') if p.is_file() or p.is_symlink()]
        after_python = snapshot(published)
        native = run(base, arguments, 'native')
        published = [p for p in base.glob('continuity.json*') if p.is_file() or p.is_symlink()]
        after_native = snapshot(published)
        keys = ['exit','stdout'] + (['category','message'] if py['exit'] == 1 else [])
        row = {'name': name, 'python': py, 'native': native,
               'inputs_unchanged': snapshot(protected) == before,
               'publication_preserved': after_native == after_python,
               'exact': all(py.get(k) == native.get(k) for k in keys) and snapshot(protected) == before
                        and after_native == after_python}
        result['unqualified' if unqualified else 'cases'].append(row)
        return row

    def fixture(name):
        base = root/name; base.mkdir()
        for name in ('old.bin','new.bin','out.bin','analysis.py','bundle.bin'):
            (base/name).write_text(name+'\n')
        state = SimpleNamespace(profile='approved-profile', input=[str(base/'old.bin')], output=[str(base/'out.bin')],
            source=['analysis='+str(base/'analysis.py')], bundled=['mapping='+str(base/'bundle.bin')], parameter=['iterations=1000'])
        original = {'version': module.state.VERSION, **module.state.input_state(state),
                    'outputs': module.state.identities(state.output)}
        save(base/'receipt.json', original)
        evidence = {}
        for name in ('plan','comparison','publication'):
            save(base/(name+'.json'), {'completed': True, 'role': name})
            evidence[name] = module.pin(base/(name+'.json'))
        proof = {'kind': module.PROOF_KIND, 'schema_version': 1, 'status': 'completed', 'profile': state.profile,
                 'old_input': module.state.identities([base/'old.bin'])[0],
                 'new_input': module.state.identities([base/'new.bin'])[0],
                 'gates': dict.fromkeys(('full_record_census_equal','full_global_order_equal',
                    'protected_annotation_fields_equal','headers_reviewed','publication_identity_exact'), True),
                 'consumer': {'ordered_rows': 123, 'old_sha256': 'a'*64, 'new_sha256': 'a'*64,
                    'role': 'das_and_dependent_pm1', 'exact': True, 'differing_rows': 0,
                    'analysis_source_sha256': original['sources'][0]['sha256']}, 'evidence': evidence}
        save(base/'proof.json', proof)
        common = ['--receipt','receipt.json','--continuity','continuity.json','--profile',state.profile,
            '--input','new.bin','--output','out.bin','--source','analysis=analysis.py',
            '--bundled','mapping=bundle.bin','--parameter','iterations=1000']
        return base, common, proof

    def recording(base, common, checksum=None):
        return ['record',*common,'--old-input','old.bin','--new-input','new.bin','--proof','proof.json',
                '--proof-sha256', checksum or hashlib.sha256((base/'proof.json').read_bytes()).hexdigest()]

    base, common, _ = fixture('roundtrip')
    arguments = recording(base, common)
    py = run(base, arguments, 'python'); target = base/'continuity.json'
    raw = target.read_bytes() if target.exists() else None
    first = snapshot([target]) if target.exists() else None
    native_check = run(base,['check',*common],'native')
    unchanged_check = first == snapshot([target]) if first else False
    native_reuse = run(base, arguments,'native')
    unchanged_reuse = first == snapshot([target]) if first else False
    if target.exists(): target.unlink()
    native = run(base,arguments,'native')
    native_bytes = target.read_bytes() if target.exists() else None
    native_mode = stat.S_IMODE(target.stat().st_mode) if target.exists() else None
    py_check = run(base,['check',*common],'python')
    result['cases'].append({'name':'roundtrip','python':py,'native':native,'cross_checks':[native_check,py_check],
        'native_reuse':native_reuse,'receipt_bytes_equal':raw==native_bytes,'mode':native_mode,
        'unchanged_check':unchanged_check,'unchanged_reuse':unchanged_reuse,
        'exact': all(x['exit']==0 for x in (py,native,native_check,py_check,native_reuse)) and
                 raw==native_bytes and native_mode==0o600 and unchanged_check and unchanged_reuse})

    mutations = [('kind','wrong'), ('schema_version',True), ('schema_version',1.0), ('status','pending'),
                 ('profile','other'), ('old_input',{}), ('new_input',{}), ('gates',{}), ('gates',None),
                 ('consumer',None), ('consumer',[]), ('consumer','text'), ('evidence',{}), ('evidence',None)]
    for ordinal,(key,value) in enumerate(mutations):
        base,common,proof=fixture(f'proof_{ordinal:02d}');proof[key]=value
        (base/'proof.json').write_text(json.dumps(proof))
        pair(base,recording(base,common),f'proof_{key}_{ordinal}')
    for key in ('full_record_census_equal','full_global_order_equal','protected_annotation_fields_equal','headers_reviewed','publication_identity_exact'):
        for value in (False,1,None):
            base,common,proof=fixture(f'gate_{key}_{value}');proof['gates'][key]=value
            (base/'proof.json').write_text(json.dumps(proof));pair(base,recording(base,common),f'{key}_{value}')
    for ordinal,(key,value) in enumerate((('role','other'),('exact',1),('differing_rows',True),('differing_rows',1),
            ('ordered_rows',False),('ordered_rows',0),('ordered_rows',1.0),('old_sha256','A'*64),('new_sha256','b'*64),
            ('analysis_source_sha256','b'*64))):
        base,common,proof=fixture(f'consumer_{ordinal}');proof['consumer'][key]=value
        (base/'proof.json').write_text(json.dumps(proof));pair(base,recording(base,common),'consumer_'+key)
    for name in ('plan','comparison','publication'):
        for corruption in ('missing','changed','badpin','linked','empty'):
            base,common,proof=fixture(f'evidence_{name}_{corruption}');path=base/(name+'.json')
            if corruption=='badpin': proof['evidence'][name]['extra']=True
            elif corruption=='missing': path.unlink()
            elif corruption=='changed': path.write_text('changed')
            elif corruption=='empty': path.write_bytes(b'')
            else:
                path.rename(base/'linked-target');path.symlink_to('linked-target')
            (base/'proof.json').write_text(json.dumps(proof));pair(base,recording(base,common),f'{name}_{corruption}')
    for name in ('changed_input','changed_output','changed_source','empty_bundle','bundle_bytes','old_equals_new',
                 'new_repeated','new_unselected','destination_alias','proof_checksum','existing_different','existing_link',
                 'existing_empty','original_wrong','original_empty'):
        base,common,proof=fixture(name);arguments=recording(base,common)
        if name.startswith('changed_'):
            chosen={'changed_input':'new.bin','changed_output':'out.bin','changed_source':'analysis.py'}[name]
            (base/chosen).write_text('different-content')
        elif name=='empty_bundle': (base/'bundle.bin').write_bytes(b'')
        elif name=='bundle_bytes': (base/'bundle.bin').write_text('new-nonempty-bytes')
        elif name=='old_equals_new': arguments[arguments.index('--old-input')+1]='new.bin'
        elif name=='new_repeated': arguments.extend(['--input','new.bin'])
        elif name=='new_unselected': arguments[arguments.index('--input')+1]='old.bin'
        elif name=='destination_alias': arguments[arguments.index('--continuity')+1]='out.bin'
        elif name=='proof_checksum': arguments[-1]='b'*64
        elif name=='existing_different': (base/'continuity.json').write_text('{}')
        elif name=='existing_link': (base/'continuity.json').symlink_to('nonexistent')
        elif name=='existing_empty': (base/'continuity.json').write_bytes(b'')
        elif name=='original_wrong': (base/'receipt.json').write_text('{}')
        elif name=='original_empty': (base/'receipt.json').write_bytes(b'')
        pair(base,arguments,name)
    for ordinal,value in enumerate((None,[],{},'text',1,True,{'kind':module.KIND},
            {'kind':module.KIND,'old_input':[]},{'kind':module.KIND,'old_input':{'path':'missing'}})):
        base,common,_=fixture(f'check_shape_{ordinal}');save(base/'continuity.json',value)
        pair(base,['check',*common],f'check_shape_{ordinal}')
    for ordinal,raw in enumerate((b'{',b'[] junk',b'{}\r\n!',b'\xef\xbb\xbf{}',b'\xff',b'{"kind":NaN}',
            b'\x00xx',b'x\x00x',b'{}\x00',b'\xef\xbb\xbf',b'\xe2\x82',b'\xf0\x9f')):
        base,common,_=fixture(f'json_{ordinal}');(base/'continuity.json').write_bytes(raw)
        pair(base,['check',*common],f'json_{ordinal}')
    for name,encoding in (('utf16','utf-16'),('utf32','utf-32')):
        base,common,_=fixture(name);(base/'continuity.json').write_bytes(json.dumps({'kind':'wrong'}).encode(encoding))
        pair(base,['check',*common],name,unqualified=True)
    result['passed']=all(row['exact'] for row in result['cases'])
    result['counts']={'qualified':len(result['cases']),'mismatches':sum(not x['exact'] for x in result['cases']),
                      'unqualified':len(result['unqualified'])}
    save(root/'comparison.json',result)
    print(json.dumps({'passed':result['passed'],**result['counts']}))
    raise SystemExit(0 if result['passed'] else 1)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    sub=parser.add_subparsers(dest='command',required=True)
    p=sub.add_parser('check')
    for option in ('producer','binary','work-root'):p.add_argument('--'+option,type=Path,required=True)
    p.set_defaults(function=check)
    p=sub.add_parser('oracle');p.add_argument('--producer',type=Path,required=True)
    p.add_argument('--exception',type=Path,required=True);p.add_argument('arguments',nargs=argparse.REMAINDER)
    p.set_defaults(function=oracle)
    args=parser.parse_args()
    if args.command=='oracle' and args.arguments[:1]==['--']:args.arguments=args.arguments[1:]
    args.function(args)


if __name__=='__main__':main()
